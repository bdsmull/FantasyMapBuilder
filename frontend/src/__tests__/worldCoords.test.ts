// ---------------------------------------------------------------------------
// The shared test world set (clients/conformance), read through Vite
// ---------------------------------------------------------------------------

const _FILES = import.meta.glob(
  ['../../../clients/conformance/**/*.json', '../../../clients/conformance/**/*.tmj'],
  { eager: true, query: '?raw', import: 'default' },
);
const _file = (suffix: string) => {
  const key = Object.keys(_FILES).find((k) => k.endsWith(suffix));
  if (!key) throw new Error(`conformance file ${suffix} not found`);
  return _FILES[key];
};

const worldSet = JSON.parse(_file('Conformance/Conformance.worldset.json')) as WorldSet;
const maps = new Map<string, TmjMap>(
  Object.entries(_FILES)
    .filter(([k]) => k.endsWith('.tmj'))
    .map(([k, text]) => [k.split('/').pop()!.replace(/\.tmj$/, ''), mapFromFile(JSON.parse(text) as TmjMap)]),
);
const lookup = (name: string): WorldMapSource | undefined => {
  const map = maps.get(name);
  const mpu = map && cellSizeMeters(map, worldSet.units);
  return map && mpu ? { map, mpu } : undefined;
};
const nodes = worldSet.nodes;

const _r = (v: number) => Math.round(v * 1e6) / 1e6;
const _pt = (p: { x: number; y: number }) => [_r(p.x), _r(p.y)];

/** The answers every implementation must give, for the inputs below. */
function computeExpected() {
  const placed = nodes.map((n) => n.mapName);
  const out: Record<string, unknown> = {
    note: 'Generated by frontend/src/__tests__/worldCoords.test.ts (UPDATE_CONFORMANCE=1). Meters, x east, y north. Compare within 1e-6.',
    worldSet: 'Conformance/Conformance.worldset.json',
    cellSizes: Object.fromEntries([...maps.keys()].sort().map((n) => [n, lookup(n)?.mpu ?? null])),
    roots: nodes.filter((n) => n.parentMapName === null).map((n) => n.mapName),
    frames: Object.fromEntries([...maps.keys()].sort().map((n) => {
      const f = mapFrame(n, nodes, lookup);
      return [n, f && { root: f.root, rect: Object.fromEntries(Object.entries(worldRect(f, maps.get(n)!)).map(([k, v]) => [k, _r(v)])) }];
    })),
    pixelToWorld: [] as unknown[],
    cellToWorld: [] as unknown[],
    worldToPixel: [] as unknown[],
    worldToCell: [] as unknown[],
    mapsAt: [] as unknown[],
    worldWidths: Object.fromEntries(nodes.filter((n) => n.parentMapName === null).map((n) => [n.mapName, worldWidth(lookup(n.mapName)!)])),
    wrapDelta: [] as unknown[],
  };
  for (const name of placed) {
    const map = maps.get(name)!;
    const frame = mapFrame(name, nodes, lookup)!;
    const size = mapPixelSize(map);
    const pixels = [[0, 0], [size.width, size.height], [size.width / 2, size.height / 2], [size.width * 0.3, size.height * 0.85], [-40, 25]];
    for (const [x, y] of pixels) {
      (out.pixelToWorld as unknown[]).push({ map: name, pixel: [x, y], world: _pt(pixelToWorld(frame, map, x, y)) });
    }
    const cells = [[0, 0], [map.width - 1, map.height - 1], [Math.floor(map.width / 2), Math.floor(map.height / 3)], [1, map.height - 2]];
    for (const [col, row] of cells) {
      const c = cellCentrePixel(map, col, row);
      const world = _pt(pixelToWorld(frame, map, c.x, c.y));
      (out.cellToWorld as unknown[]).push({ map: name, cell: [col, row], world });
      (out.worldToCell as unknown[]).push({ map: name, world, cell: [col, row] });
    }
    for (const [x, y] of [[size.width * 0.62, size.height * 0.41], [3, 4]]) {
      const world = _pt(pixelToWorld(frame, map, x, y));
      (out.worldToPixel as unknown[]).push({ map: name, world, pixel: _pt(worldToPixel(frame, map, world[0], world[1])) });
    }
    // Off the map: no cell
    const off = pixelToWorld(frame, map, -size.width, -size.height);
    (out.worldToCell as unknown[]).push({ map: name, world: _pt(off), cell: null });
  }
  const cityFrame = mapFrame('city', nodes, lookup)!;
  const city = maps.get('city')!;
  const cityMid = pixelToWorld(cityFrame, city, mapPixelSize(city).width / 2, mapPixelSize(city).height / 2);
  const islandFrame = mapFrame('island', nodes, lookup)!;
  const cellar = maps.get('cellar')!;
  const cellarMid = pixelToWorld(mapFrame('cellar', nodes, lookup)!, cellar, mapPixelSize(cellar).width / 2, mapPixelSize(cellar).height / 2);
  const points: [string, number, number][] = [
    ['world', 0, 0],
    ['world', _r(cityMid.x), _r(cityMid.y)],
    ['world', _r(cellarMid.x), _r(cellarMid.y)],
    ['world', 1e9, 1e9],
    ['island', 0, 0],
    ['island', _r(pixelToWorld(islandFrame, maps.get('island')!, 10, 10).x), _r(pixelToWorld(islandFrame, maps.get('island')!, 10, 10).y)],
  ];
  // Worlds that wrap: the same place, some turns away
  for (const name of ['ring', 'straits', 'isle', 'band', 'hexring', 'pointring', 'oddring']) {
    const map = maps.get(name)!, frame = mapFrame(name, nodes, lookup)!;
    const turnM = frame.circumference ?? map.width * frame.mpu;
    for (const [col, row] of [[0, 1], [map.width - 1, map.height - 1], [2, 0]]) {
      const c = cellCentrePixel(map, col, row);
      const at = pixelToWorld(frame, map, c.x + 0.13 * map.tilewidth, c.y - 0.11 * map.tileheight);
      for (const turns of [-2, -1, 1, 3]) {
        const world = _pt({ x: at.x + turns * turnM, y: at.y });
        const cell = worldToCell(frame, map, world[0], world[1]);
        (out.worldToCell as unknown[]).push({ map: name, world, cell: cell && [cell.col, cell.row] });
        (out.worldToPixel as unknown[]).push({ map: name, world, pixel: _pt(worldToPixel(frame, map, world[0], world[1])) });
      }
    }
  }
  const straits = maps.get('straits')!, straitsFrame = mapFrame('straits', nodes, lookup)!;
  const size = mapPixelSize(straits);
  for (const f of [0.1, 0.5, 0.95]) {
    const at = pixelToWorld(straitsFrame, straits, size.width * f, size.height * 0.4);
    for (const turns of [0, 1, -1, 5]) points.push(['ring', _r(at.x + turns * 16_000), _r(at.y)]);
  }
  for (const root of ['hexring', 'pointring', 'oddring']) {
    const map = maps.get(root)!, frame = mapFrame(root, nodes, lookup)!;
    const r = worldRect(frame, map);
    for (const x of [r.west - 500, r.east + 500, r.east + 7_000]) points.push([root, _r(x), _r((r.north + r.south) / 2)]);
  }
  for (const root of ['world', 'ring', 'pointring']) {
    const width = worldWidth(lookup(root)!);
    for (const [from, to] of [[0, 900], [-7_500, 7_300], [7_300, -7_500], [100, 8_100], [8_100, 100], [0, 40_100], [3, 3]]) {
      (out.wrapDelta as unknown[]).push({ root, from, to, delta: _r(wrapDelta(from, to, width)) });
    }
  }
  for (const [root, x, y] of points) {
    (out.mapsAt as unknown[]).push({
      root, world: [x, y],
      maps: mapsAt(root, x, y, nodes, lookup).map((m) => ({ name: m.name, z: m.z, pixel: _pt(m.pixel) })),
    });
  }
  return out;
}

// ---------------------------------------------------------------------------
// Tests
// ---------------------------------------------------------------------------

const square: TmjMap = {
  orientation: 'orthogonal', width: 10, height: 6, tilewidth: 32, tileheight: 32,
  nextlayerid: 1, nextobjectid: 1, tilesets: [], layers: [],
};

describe('world coordinates', () => {
  const root = { map: square, mpu: 100 };
  const child: TmjMap = { ...square, width: 4, height: 4 };
  const ns: WorldSetNode[] = [
    { mapName: 'root', parentMapName: null, parentAnchor: null, z: 0 },
    { mapName: 'child', parentMapName: 'root', parentAnchor: { col: 2, row: 1 }, z: 0 },
  ];
  const look = (n: string) => (n === 'root' ? root : n === 'child' ? { map: child, mpu: 25 } : undefined);

  it('a root without an origin object has it at its centre; north is positive', () => {
    const f = mapFrame('root', ns, look)!;
    expect(pixelToWorld(f, square, 160, 96)).toEqual({ x: 0, y: 0 });
    expect(pixelToWorld(f, square, 0, 0)).toEqual({ x: -500, y: 300 });
    expect(pixelToWorld(f, square, 320, 192)).toEqual({ x: 500, y: -300 });
  });

  it('children sit where their placement puts them', () => {
    // A 4-cell, 25 m child is one 100 m parent cell: cell (2, 1), so its top-left is at (200, 100) m
    const f = mapFrame('child', ns, look)!;
    expect(pixelToWorld(f, child, 0, 0)).toEqual({ x: 200 - 500, y: 300 - 100 });
    const back = worldToPixel(f, child, -300, 200);
    expect(back.x).toBeCloseTo(0);
    expect(back.y).toBeCloseTo(0);
  });

  it('the origin object moves world (0, 0)', () => {
    const withOrigin: TmjMap = {
      ...square,
      layers: [{ type: 'objectgroup', id: 1, name: 'World', visible: true, opacity: 1, offsetx: 0, offsety: 0, color: '#e8c547',
        objects: [{ id: 1, name: 'World origin', type: WORLD_ORIGIN_TYPE, x: 32, y: 64, width: 0, height: 0, visible: true, point: true }] }],
    };
    expect(findWorldOrigin(withOrigin)?.object.id).toBe(1);
    expect(originPixel(withOrigin)).toEqual({ x: 32, y: 64 });
    const f = mapFrame('root', ns, (n) => (n === 'root' ? { map: withOrigin, mpu: 100 } : look(n)))!;
    expect(pixelToWorld(f, withOrigin, 32, 64)).toEqual({ x: 0, y: 0 });
    expect(pixelToWorld(f, withOrigin, 64, 32)).toEqual({ x: 100, y: 100 });
  });

  it('maps outside the world set, or with a missing parent, have no frame', () => {
    expect(mapFrame('nowhere', ns, look)).toBeNull();
    expect(mapFrame('child', ns, (n) => (n === 'child' ? look(n) : undefined))).toBeNull();
  });

  it('cells: square ones by containment, off the map is none', () => {
    expect(pixelToCellIndex(square, 33, 70)).toEqual({ col: 1, row: 2 });
    expect(pixelToCellIndex(square, -1, 5)).toBeNull();
    expect(defaultOriginPixel(square)).toEqual({ x: 160, y: 96 });
  });

  it('on a wrapped root, x repeats: any turn finds the same cell, and positions never jump', () => {
    const ring: TmjMap = { ...square, properties: [{ name: 'wrapX', type: 'bool', value: true }] };
    const wrapped = (n: string) => (n === 'root' ? { map: ring, mpu: 100 } : look(n));
    const f = mapFrame('root', ns, wrapped)!;
    expect(f.circumference).toBe(1000);
    expect(pixelToWorld(f, ring, 330, 96).x).toBeCloseTo(531.25); // past the east edge, continuous
    for (const x of [-450, 550, -1450, 10_550]) expect(worldToCell(f, ring, x, 0)).toEqual({ col: 0, row: 3 });
    expect(worldToCell(f, ring, 500, 0)).toEqual({ col: 0, row: 3 }); // the east edge is the west edge
    expect(worldToCell(f, ring, 0, 301)).toBeNull(); // north of the world
    expect(mapsAt('root', 1_000 - 250, 150, ns, wrapped).map((m) => m.name)).toEqual(['child', 'root']);
    expect(wrapDelta(450, -450, 1000)).toBe(100);
    expect(wrapDelta(-450, 450, 1000)).toBe(-100);
    expect(wrapDelta(0, 500, 1000)).toBe(-500);
    expect(wrapDelta(0, 1500, null)).toBe(1500);
    expect(mapFrame('root', ns, look)!.circumference).toBeNull();
  });

  it('formats coordinates as finely as the map can use, however far from the origin', () => {
    expect(formatDistance(-9_778_271.5, 'metric', 1)).toBe('−9,778,271.5 m'); // a room on a far continent
    expect(formatDistance(-9_778_271.5, 'metric', 250)).toBe('−9,778,272 m');
    expect(formatDistance(-9_778_271.5, 'metric', 500_000)).toBe('−9,778.27 km');
    expect(formatDistance(1609.344 * 10, 'imperial', 5000)).toBe('10.00 mi');
    expect(formatDistance(0.3048 * 10, 'imperial', 2)).toBe('10.0 ft');
    expect(formatDistance(-0.001, 'metric', 1)).toBe('0.0 m');
  });

  it('the editor adds the origin at the centre, and moving it is one undo step', () => {
    useMapStore.setState({ mapData: { ...square, layers: [], nextobjectid: 5, nextlayerid: 2 }, past: [], future: [] });
    expect(useMapStore.getState().ensureWorldOrigin()).toBe(true);
    expect(useMapStore.getState().ensureWorldOrigin()).toBe(false);
    const placed = findWorldOrigin(useMapStore.getState().mapData!)!;
    expect(placed.object).toMatchObject({ id: 5, x: 160, y: 96, type: WORLD_ORIGIN_TYPE, point: true });
    expect(useMapStore.getState().past).toHaveLength(0);
    useMapStore.getState().setWorldOrigin(10, 20);
    expect(findWorldOrigin(useMapStore.getState().mapData!)!.object).toMatchObject({ id: 5, x: 10, y: 20 });
    useMapStore.getState().undo();
    expect(findWorldOrigin(useMapStore.getState().mapData!)!.object).toMatchObject({ x: 160, y: 96 });
  });
});

describe('conformance (clients/conformance/expected.json)', () => {
  it('cell sizes follow metersPerUnit, then the scale table', () => {
    expect(lookup('city')?.mpu).toBeCloseTo(660 * 0.3048); // imperial city, no metersPerUnit in the file
    expect(lookup('island')?.mpu).toBe(750);
  });

  it('the reference implementation matches expected.json', async () => {
    const expected = computeExpected();
    const env = (globalThis as { process?: { env?: Record<string, string | undefined> } }).process?.env ?? {};
    if (env.UPDATE_CONFORMANCE) {
      const fs = await import(/* @vite-ignore */ 'node:fs' as string);
      fs.writeFileSync(new URL('../../../clients/conformance/expected.json', import.meta.url), JSON.stringify(expected, null, 2) + '\n');
      return; // the file read at the top is the old one
    }
    expect(JSON.parse(_file('conformance/expected.json'))).toEqual(JSON.parse(JSON.stringify(expected)));
  });
});
